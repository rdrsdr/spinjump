"""Exporta a configuração padrão, os presets e as faixas válidas para o simulador no navegador.

A fonte da verdade continua em ``configs/default.yaml``, ``configs/presets/*.yaml`` e nos tipos
Pydantic de ``spinjump/config.py``; este script só os converte em ``public/config.json``, que o
JavaScript usa para montar o formulário, validar os valores e gerar o modelo.

Uso (no container de desenvolvimento): ./dev.sh python browser/tools/export_config.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from spinjump.config import DEFAULT_CONFIG, PRESET_DIR, SimConfig, list_presets  # noqa: E402

OUT = ROOT / "browser" / "public" / "config.json"


def flat_rules(schema: dict) -> dict:
    """Regras por caminho ("rope.length_m" → tipo, limites, opções) a partir do JSON Schema do Pydantic."""
    defs = schema["$defs"]
    rules = {}
    for sec, ref in schema["properties"].items():
        if "$ref" not in ref:
            continue
        for key, prop in defs[ref["$ref"].split("/")[-1]]["properties"].items():
            r = {}
            alts = prop.get("anyOf", [prop])
            for a in alts:
                if a.get("type") == "null":
                    r["nullable"] = True
                elif "const" in a:
                    r.setdefault("consts", []).append(a["const"])
                else:
                    if "enum" in a:
                        r["enum"] = a["enum"]
                    r["type"] = a.get("type")
                    for k in ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems"):
                        if k in a:
                            r[k] = a[k]
            rules[f"{sec}.{key}"] = r
    return rules


def main() -> None:
    presets = []
    for name in list_presets():
        data = yaml.safe_load((PRESET_DIR / f"{name}.yaml").read_text()) or {}
        desc = data.pop("description_en", None) or data.pop("description", "")
        data.pop("description", None)
        presets.append(dict(name=name, description=desc, overrides=data))
    out = dict(
        note="Generated by browser/tools/export_config.py from configs/*.yaml and spinjump/config.py; do not edit.",
        defaults=yaml.safe_load(Path(DEFAULT_CONFIG).read_text()),
        presets=presets,
        rules=flat_rules(SimConfig.model_json_schema()),
    )
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False))
    print(f"{OUT.relative_to(ROOT)}: {len(presets)} presets, {len(out['rules'])} parâmetros")


if __name__ == "__main__":
    main()
